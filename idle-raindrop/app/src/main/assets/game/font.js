FONT_SRC.trim().split('\n').forEach(function (l) {
  var p = l.split(' '), ch = p.shift(), y = -1;
  if (p[0][0] === '@') y = +p.shift().slice(1);
  if (y < 0) y = 7 - p.length;
  FONT[ch] = { w: p[0].length, y: y, rows: p };
});
FONT[' '] = { w: 2, y: 0, rows: [] };
